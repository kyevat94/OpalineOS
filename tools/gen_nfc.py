"""Generates kernel/lib/nfc_table.h: pairs (base letter, combining mark) -> precomposed character.

The kernel uses it to store file names in NFC (e.g. "a" + U+0303 -> "ã"). It covers the Latin,
Greek and Cyrillic letters the console font has, which is what file names typed on OpalineOS
can contain today. Full Unicode normalization comes with the text stack (stage E12).

    python tools/gen_nfc.py
"""
import os
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "kernel", "lib", "nfc_table.h")

BASES = list(range(0x41, 0x5B)) + list(range(0x61, 0x7B)) + list(range(0xC0, 0x250)) + \
        list(range(0x370, 0x400)) + list(range(0x400, 0x530)) + list(range(0x1E00, 0x1F00))
MARKS = range(0x300, 0x370)


def main():
    pairs = []
    for base in BASES:
        for mark in MARKS:
            s = unicodedata.normalize("NFC", chr(base) + chr(mark))
            if len(s) == 1 and ord(s) != base:
                pairs.append((base, mark, ord(s)))
    pairs.sort()
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later",
        " * Copyright (C) 2026 The OpalineOS authors */",
        "/* Generated by tools/gen_nfc.py from Python's Unicode " + unicodedata.unidata_version + " data. Do not edit. */",
        "/* { base, combining mark, precomposed }, sorted by base then mark */",
        "static const struct { u32 base, mark, composed; } nfc_pairs[] = {",
    ]
    for b, m, c in pairs:
        lines.append(f"    {{0x{b:04X}, 0x{m:04X}, 0x{c:04X}}},")
    lines.append("};")
    with open(OUT, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"OK: {OUT}: {len(pairs)} pairs")


if __name__ == "__main__":
    main()
